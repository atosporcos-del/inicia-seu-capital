export const getArticlesByCategory = (category) => {
  return articles.filter(article => article.category === category);
};

export const getArticleBySlug = (slug) => {
  return articles.find(article => article.slug === slug);
};

export const getFeaturedArticles = () => {
  // First priority: items explicitly marked as featured
  const explicitFeatured = articles.filter(article => article.featured);
  
  if (explicitFeatured.length > 0) {
    // Fill the rest with category representatives if we have less than 3 featured
    if (explicitFeatured.length < 3) {
      const economia = articles.find(a => a.category === 'Economia' && !a.featured);
      const financas = articles.find(a => a.category === 'Finanças' && !a.featured);
      const carreira = articles.find(a => a.category === 'Carreira' && !a.featured);
      const fillers = [economia, financas, carreira].filter(Boolean);
      return [...explicitFeatured, ...fillers].slice(0, 3);
    }
    return explicitFeatured.slice(0, 3);
  }

  // Fallback: One from each main category
  const economia = articles.find(a => a.category === 'Economia');
  const financas = articles.find(a => a.category === 'Finanças');
  const carreira = articles.find(a => a.category === 'Carreira');
  return [economia, financas, carreira].filter(Boolean);
};